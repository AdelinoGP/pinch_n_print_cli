#!/usr/bin/env python3
"""Reduce the t163 three-tool campaign into the artifact the map quotes.

In-repo inputs (required):
  docs/specs/perf-vs-orca/evidence/t151-skirt-hull-contour/reference.json
  <this dir>/reduced/load-samples.csv

Raw inputs (gitignored, regenerated by run_scoreboard.ps1):
  target/matched-pair/t163-accelerated-board/scoreboard-rows.csv
  target/matched-pair/t163-accelerated-board/*.stderr.jsonl

Writes reduced/summary.json.

Definitions (identical to reduce_t145.py / reduce_t161.py so tables compare):
  ratio                      = median(PnP wall) / median(Orca wall)
  accel_vs_ordinary_wall_pct = 100 * (median(accel wall) / median(ordinary wall) - 1)
"""

import csv
import json
import os
import statistics
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", "..", "..", ".."))
REF = os.path.join(
    REPO,
    "docs",
    "specs",
    "perf-vs-orca",
    "evidence",
    "t151-skirt-hull-contour",
    "reference.json",
)
RUN_DIR = os.path.join(REPO, "target", "matched-pair", "t163-accelerated-board")
CSV = os.path.join(RUN_DIR, "scoreboard-rows.csv")
LOAD = os.path.join(HERE, "reduced", "load-samples.csv")
OUT = os.path.join(HERE, "reduced", "summary.json")

CELL_ORDER = [
    "benchy-classic-off",
    "benchy-classic-on",
    "benchy-arachne-off",
    "benchy-arachne-on",
    "base-classic-off",
    "base-classic-on",
    "base-arachne-off",
    "base-arachne-on",
]
TOOLS = ["orca", "pnp-ordinary", "pnp-accelerated"]

EXPECTED_KEYS = {
    "resolved_brim_width": "8",
    "resolved_brim_type": "outer_only",
    "resolved_skirt_loops": "6",
    "resolved_skirt_distance": "3",
    "resolved_skirt_height": "1",
    "resolved_initial_layer_line_width": "0.4",
    "resolved_tree_support_brim_width": "0",
    "resolved_enable_arc_fitting": "disabled",
    "resolved_elefant_foot_compensation": "0",
}


def fnum(v):
    v = (v or "").strip()
    if not v:
        return None
    try:
        return float(v)
    except ValueError:
        return None


def spread_pct(values):
    if len(values) < 2:
        return None
    m = statistics.median(values)
    if not m:
        return None
    return round(100.0 * (max(values) - min(values)) / m, 2)


def arm_block(rows, tool):
    walls = [fnum(r["wall_seconds"]) for r in rows if r.get("tool") == tool]
    cpus = [fnum(r["cpu_seconds"]) for r in rows if r.get("tool") == tool]
    if not walls:
        return None
    return {
        "runs": len(walls),
        "wall_s": [round(w, 4) for w in walls],
        "cpu_s": [round(c, 4) for c in cpus],
        "wall_median_s": round(statistics.median(walls), 4),
        "cpu_median_s": round(statistics.median(cpus), 4),
        "wall_spread_pct": spread_pct(walls),
        "cpu_spread_pct": spread_pct(cpus),
    }


def main():
    if not os.path.exists(CSV):
        sys.exit("missing campaign csv: %s" % CSV)
    with open(CSV, newline="", encoding="utf-8-sig") as f:
        all_rows = list(csv.DictReader(f))
    ref = json.load(open(REF, encoding="utf-8"))["active_set"]

    measured = [r for r in all_rows if r.get("warmup") == "0"]
    warmups = [r for r in all_rows if r.get("warmup") == "1"]

    cells = {}
    for cell in CELL_ORDER:
        fixture, generator, supports = cell.split("-")
        rows = [
            r
            for r in measured
            if r.get("fixture") == fixture
            and r.get("cell") == generator + "-" + supports
        ]
        entry = {"fixture": fixture, "generator": generator, "supports": supports}

        for tool in TOOLS:
            block = arm_block(rows, tool)
            if block:
                entry[tool] = block

        ordinary, accelerated = entry.get("pnp-ordinary"), entry.get("pnp-accelerated")
        orca = entry.get("orca")
        if ordinary and orca:
            entry["ratio_ordinary_over_orca"] = round(
                ordinary["wall_median_s"] / orca["wall_median_s"], 4
            )
            entry["required_cut_ordinary_pct"] = round(
                100 * (1 - 1 / entry["ratio_ordinary_over_orca"]), 2
            )
        if accelerated and orca:
            entry["ratio_accelerated_over_orca"] = round(
                accelerated["wall_median_s"] / orca["wall_median_s"], 4
            )
            entry["required_cut_accelerated_pct"] = round(
                100 * (1 - 1 / entry["ratio_accelerated_over_orca"]), 2
            )
        if ordinary and accelerated:
            entry["accel_vs_ordinary_wall_pct"] = round(
                100 * (accelerated["wall_median_s"] / ordinary["wall_median_s"] - 1), 2
            )
            entry["accel_vs_ordinary_cpu_pct"] = round(
                100 * (accelerated["cpu_median_s"] / ordinary["cpu_median_s"] - 1), 2
            )

        for tool, key in (
            ("pnp-ordinary", "ordinary"),
            ("pnp-accelerated", "accelerated"),
        ):
            hashes = sorted(
                {
                    (r.get("sha256_of_gcode") or "").strip()
                    for r in rows
                    if r.get("tool") == tool
                }
            )
            hashes = [h for h in hashes if h]
            entry["identity_" + key] = bool(ref.get(cell)) and hashes == [ref[cell]]
            entry["hash_" + key] = hashes[0] if len(hashes) == 1 else hashes
            entry["exit_codes_" + key] = sorted(
                {r.get("exit_code", "") for r in rows if r.get("tool") == tool}
            )
            entry["degraded_" + key] = sorted(
                {r.get("degraded", "") for r in rows if r.get("tool") == tool}
            )
        entry["reference_hash"] = ref.get(cell)

        orca_rows = [r for r in rows if r.get("tool") == "orca"]
        key_audit = {}
        for key, want in EXPECTED_KEYS.items():
            got = sorted({(r.get(key) or "").strip() for r in orca_rows})
            key_audit[key] = {
                "expected": want,
                "resolved": got,
                "ok": got == [want] if got else False,
            }
        entry["orca_matched_keys"] = key_audit
        entry["orca_matched_keys_ok"] = all(v["ok"] for v in key_audit.values())
        entry["orca_exit_codes"] = sorted({r.get("exit_code", "") for r in orca_rows})

        cells[cell] = entry

    def collect(key):
        return [v[key] for v in cells.values() if key in v]

    ord_ratios = collect("ratio_ordinary_over_orca")
    acc_ratios = collect("ratio_accelerated_over_orca")
    deltas = collect("accel_vs_ordinary_wall_pct")
    cpu_deltas = collect("accel_vs_ordinary_cpu_pct")

    load = []
    if os.path.exists(LOAD):
        with open(LOAD, newline="", encoding="utf-8-sig") as f:
            for r in csv.reader(f):
                if len(r) >= 2 and r[1].strip():
                    load.append(r)
    load_pcts = [float(r[1]) for r in load if fnum(r[1]) is not None]

    summary = {
        "ticket": 163,
        "generated_by": "reduce_t163.py",
        "question": "Three-tool eight-cell board: accelerated arm vs ordinary vs Orca, one window.",
        "raw_sources": {
            "campaign_csv": os.path.relpath(CSV, REPO).replace("\\", "/"),
            "load_samples": os.path.relpath(LOAD, REPO).replace("\\", "/"),
        },
        "currency_artifact": os.path.relpath(REF, REPO).replace("\\", "/"),
        "protocol": {
            "cells": 8,
            "tools": TOOLS,
            "runs_per_cell_tool": 3,
            "warmups_per_cell_tool": 1,
            "interleaved": True,
            "measured_rows": len(measured),
            "warmup_rows": len(warmups),
        },
        "cells": cells,
        "ranges": {
            "ratio_ordinary_over_orca": [
                round(min(ord_ratios), 4),
                round(max(ord_ratios), 4),
            ]
            if ord_ratios
            else None,
            "ratio_accelerated_over_orca": [
                round(min(acc_ratios), 4),
                round(max(acc_ratios), 4),
            ]
            if acc_ratios
            else None,
            "accel_vs_ordinary_wall_pct": [min(deltas), max(deltas)]
            if deltas
            else None,
            "accel_vs_ordinary_cpu_pct": [min(cpu_deltas), max(cpu_deltas)]
            if cpu_deltas
            else None,
        },
        "identity": {
            "ordinary_all_eight": all(v["identity_ordinary"] for v in cells.values()),
            "accelerated_all_eight": all(
                v["identity_accelerated"] for v in cells.values()
            ),
            "ordinary_missing": [
                k for k, v in cells.items() if not v["identity_ordinary"]
            ],
            "accelerated_missing": [
                k for k, v in cells.items() if not v["identity_accelerated"]
            ],
        },
        "matched_keys": {
            "all_eight": all(v["orca_matched_keys_ok"] for v in cells.values())
        },
        "box_load_pct": {
            "samples": len(load_pcts),
            "min": round(min(load_pcts), 1) if load_pcts else None,
            "median": round(statistics.median(load_pcts), 1) if load_pcts else None,
            "max": round(max(load_pcts), 1) if load_pcts else None,
        },
        "cells_accelerated_faster": sum(1 for d in deltas if d < 0),
        "cells_accelerated_slower": sum(1 for d in deltas if d > 0),
    }

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    json.dump(summary, open(OUT, "w", encoding="utf-8"), indent=1)

    print("wrote %s" % OUT)
    for cell in CELL_ORDER:
        c = cells[cell]
        if "pnp-ordinary" not in c or "pnp-accelerated" not in c:
            print("%-22s INCOMPLETE" % cell)
            continue
        print(
            "%-22s ord %8.3f  acc %8.3f  orca %8.3f | %5.3fx / %5.3fx | acc-vs-ord %+6.1f%% | id %s/%s"
            % (
                cell,
                c["pnp-ordinary"]["wall_median_s"],
                c["pnp-accelerated"]["wall_median_s"],
                c["orca"]["wall_median_s"],
                c.get("ratio_ordinary_over_orca", 0),
                c.get("ratio_accelerated_over_orca", 0),
                c.get("accel_vs_ordinary_wall_pct", 0),
                "OK" if c["identity_ordinary"] else "MISS",
                "OK" if c["identity_accelerated"] else "MISS",
            )
        )
    print(
        "identity ordinary 8/8: %s   accelerated 8/8: %s   matched keys 8/8: %s"
        % (
            summary["identity"]["ordinary_all_eight"],
            summary["identity"]["accelerated_all_eight"],
            summary["matched_keys"]["all_eight"],
        )
    )


if __name__ == "__main__":
    main()
