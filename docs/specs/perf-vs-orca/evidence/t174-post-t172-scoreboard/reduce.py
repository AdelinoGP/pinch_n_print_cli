def fnum(v):
    v = (v or "").strip()
    if not v:
        return None
    try:
        return float(v)
    except ValueError:
        return None


def spread_pct(values):
    if len(values) < 2:
        return None
    m = statistics.median(values)
    if not m:
        return None
    return round(100.0 * (max(values) - min(values)) / m, 2)


def count_code_1200(stderr_path):
    if not stderr_path or not os.path.exists(stderr_path):
        return None
    hits = 0
    with open(stderr_path, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            if (
                '"code":1200' in line
                or '"code": 1200' in line
                or "exact-Z occupancy" in line
            ):
                hits += 1
    return hits


def read_support_style(run_dir, run_id):
    p = os.path.join(run_dir, "stats", run_id + ".json")
    if not os.path.exists(p):
        return None
    with open(p, encoding="utf-8-sig") as fh:
        data = json.load(fh)
    return (data.get("appendix") or {}).get("support_style")


def arm_block(rows, tool):
    trows = [r for r in rows if r.get("tool") == tool]
    walls = [fnum(r["wall_seconds"]) for r in trows]
    cpus = [fnum(r["cpu_seconds"]) for r in trows]
    ratios = [fnum(r["cpu_wall_ratio"]) for r in trows]
    if not walls:
        return None
    best_ratio = max(ratios)
    starved = [i for i, r in enumerate(ratios) if best_ratio and r < 0.75 * best_ratio]
    return {
        "runs": len(walls),
        "wall_s": [round(w, 4) for w in walls],
        "cpu_s": [round(c, 4) for c in cpus],
        "cpu_wall_ratio": [round(r, 4) for r in ratios],
        "wall_median_s": round(statistics.median(walls), 4),
        "cpu_median_s": round(statistics.median(cpus), 4),
        "cpu_wall_ratio_median": round(statistics.median(ratios), 4),
        "wall_spread_pct": spread_pct(walls),
        "cpu_spread_pct": spread_pct(cpus),
        "starved_indices_075": starved,
    }


def reduce_batch(batch_id, load_path, out_path, window_label):
    run_dir = os.path.join(REPO, "target", "matched-pair", batch_id)
    csv_path = os.path.join(run_dir, "scoreboard-rows.csv")
    if not os.path.exists(csv_path):
        sys.exit("missing campaign csv: %s" % csv_path)

    with open(csv_path, newline="", encoding="utf-8-sig") as f:
        all_rows = list(csv.DictReader(f))
    with open(REF, encoding="utf-8") as f:
        ref_doc = json.load(f)
    ref_hashes = ref_doc["active_set"]
    ref_bytes = ref_doc["bytes"]

    measured = [r for r in all_rows if r.get("warmup") == "0"]
    warmups = [r for r in all_rows if r.get("warmup") == "1"]

    cells = {}
    for cell in CELL_ORDER:
        fixture, generator, supports = cell.split("-")
        m_rows = [
            r
            for r in measured
            if r.get("fixture") == fixture
            and r.get("cell") == generator + "-" + supports
        ]
        all_cell_rows = [
            r
            for r in all_rows
            if r.get("fixture") == fixture
            and r.get("cell") == generator + "-" + supports
        ]
        entry = {"fixture": fixture, "generator": generator, "supports": supports}

        for tool in TOOLS:
            block = arm_block(m_rows, tool)
            if block:
                entry[tool] = block

        ordinary = entry.get("pnp-ordinary")
        accelerated = entry.get("pnp-accelerated")
        orca = entry.get("orca")

        if ordinary and orca:
            wr = ordinary["wall_median_s"] / orca["wall_median_s"]
            cr = ordinary["cpu_median_s"] / orca["cpu_median_s"]
            entry["ratio_ordinary_over_orca"] = round(wr, 4)
            entry["cpu_ratio_ordinary_over_orca"] = round(cr, 4)
            entry["required_cut_ordinary_pct"] = round(100.0 * (1.0 - 1.0 / wr), 2)
            entry["wall_win_ordinary"] = ordinary["wall_median_s"] < orca["wall_median_s"]
            entry["strict_separation_ordinary"] = (
                max(ordinary["wall_s"]) < min(orca["wall_s"])
            )
            entry["cpu_corroborates_ordinary"] = (
                ordinary["cpu_median_s"] < orca["cpu_median_s"]
            )
            entry["destination_win_ordinary"] = (
                entry["wall_win_ordinary"] and entry["cpu_corroborates_ordinary"]
            )
        if accelerated and orca:
            wr = accelerated["wall_median_s"] / orca["wall_median_s"]
            cr = accelerated["cpu_median_s"] / orca["cpu_median_s"]
            entry["ratio_accelerated_over_orca"] = round(wr, 4)
            entry["cpu_ratio_accelerated_over_orca"] = round(cr, 4)
            entry["required_cut_accelerated_pct"] = round(100.0 * (1.0 - 1.0 / wr), 2)
            entry["wall_win_accelerated"] = (
                accelerated["wall_median_s"] < orca["wall_median_s"]
            )
            entry["strict_separation_accelerated"] = (
                max(accelerated["wall_s"]) < min(orca["wall_s"])
            )
            entry["cpu_corroborates_accelerated"] = (
                accelerated["cpu_median_s"] < orca["cpu_median_s"]
            )
            entry["destination_win_accelerated"] = (
                entry["wall_win_accelerated"] and entry["cpu_corroborates_accelerated"]
            )
        if ordinary and accelerated:
            entry["accel_vs_ordinary_wall_pct"] = round(
                100.0 * (accelerated["wall_median_s"] / ordinary["wall_median_s"] - 1.0),
                2,
            )
            entry["accel_vs_ordinary_cpu_pct"] = round(
                100.0 * (accelerated["cpu_median_s"] / ordinary["cpu_median_s"] - 1.0),
                2,
            )
        entry["t172_estimated_ratio_ordinary"] = T172_ESTIMATES[cell]

        for tool, key in (
            ("pnp-ordinary", "ordinary"),
            ("pnp-accelerated", "accelerated"),
        ):
            t_all = [r for r in all_cell_rows if r.get("tool") == tool]
            hashes = sorted(
                {
                    (r.get("sha256_of_gcode") or "").strip()
                    for r in t_all
                    if r.get("sha256_of_gcode")
                }
            )
            gbytes = sorted(
                {int(r["gcode_bytes"]) for r in t_all if r.get("gcode_bytes")}
            )
            code1200 = [count_code_1200(r.get("stderr_path")) for r in t_all]
            code1200_total = sum(c for c in code1200 if c is not None)
            entry["identity_" + key] = (
                bool(ref_hashes.get(cell))
                and hashes == [ref_hashes[cell]]
                and gbytes == [ref_bytes[cell]]
                and len(t_all) == 4
            )
            entry["hash_" + key] = hashes[0] if len(hashes) == 1 else hashes
            entry["gcode_bytes_" + key] = gbytes[0] if len(gbytes) == 1 else gbytes
            entry["exit_codes_" + key] = sorted({r.get("exit_code", "") for r in t_all})
            entry["degraded_" + key] = sorted({r.get("degraded", "") for r in t_all})
            entry["fatal_error_counts_" + key] = sorted(
                {r.get("fatal_error_count", "") for r in t_all}
            )
            entry["non_fatal_error_counts_" + key] = sorted(
                {r.get("non_fatal_error_count", "") for r in t_all}
            )
            entry["code_1200_count_" + key] = code1200_total

        entry["reference_hash"] = ref_hashes.get(cell)
        entry["reference_bytes"] = ref_bytes.get(cell)

        orca_all = [r for r in all_cell_rows if r.get("tool") == "orca"]
        key_audit = {}
        for key, want in EXPECTED_KEYS.items():
            got = sorted({(r.get(key) or "").strip() for r in orca_all})
            key_audit[key] = {
                "expected": want,
                "resolved": got,
                "ok": got == [want] if got else False,
            }
        want_style = "tree_strong" if supports == "on" else "default"
        styles = sorted(
            {
                s
                for s in (read_support_style(run_dir, r["run_id"]) for r in orca_all)
                if s is not None
            }
        )
        key_audit["resolved_support_style"] = {
            "expected": want_style,
            "resolved": styles,
            "ok": styles == [want_style] if styles else False,
        }
        entry["orca_matched_keys"] = key_audit
        entry["orca_matched_keys_ok"] = all(v["ok"] for v in key_audit.values())
        entry["orca_exit_codes"] = sorted({r.get("exit_code", "") for r in orca_all})
        entry["orca_gcode_bytes"] = sorted(
            {int(r["gcode_bytes"]) for r in orca_all if r.get("gcode_bytes")}
        )

        cells[cell] = entry

    def collect(key):
        return [v[key] for v in cells.values() if key in v]

    ord_ratios = collect("ratio_ordinary_over_orca")
    acc_ratios = collect("ratio_accelerated_over_orca")
    ord_cpu_ratios = collect("cpu_ratio_ordinary_over_orca")
    acc_cpu_ratios = collect("cpu_ratio_accelerated_over_orca")
    deltas = collect("accel_vs_ordinary_wall_pct")
    cpu_deltas = collect("accel_vs_ordinary_cpu_pct")

    load_rows = []
    if load_path and os.path.exists(load_path):
        with open(load_path, newline="", encoding="utf-8-sig") as f:
            for r in csv.reader(f):
                if len(r) >= 2 and r[1].strip():
                    load_rows.append(r)
    load_pcts = [float(r[1]) for r in load_rows if fnum(r[1]) is not None]
    free_mb = [
        float(r[2]) / 1024.0
        for r in load_rows
        if len(r) >= 3 and fnum(r[2]) is not None
    ]

    timestamps = [r.get("timestamp_utc", "") for r in all_rows if r.get("timestamp_utc")]

    ord_wall_wins = [c for c in CELL_ORDER if cells[c].get("wall_win_ordinary")]
    ord_dest_wins = [c for c in CELL_ORDER if cells[c].get("destination_win_ordinary")]
    acc_wall_wins = [c for c in CELL_ORDER if cells[c].get("wall_win_accelerated")]
    acc_dest_wins = [c for c in CELL_ORDER if cells[c].get("destination_win_accelerated")]

    summary = {
        "ticket": 174,
        "window": window_label,
        "batch_id": batch_id,
        "generated_by": "reduce.py",
        "question": (
            "Post-t172 three-tool eight-cell board (OrcaSlicer 2.5.1 vs PnP ordinary "
            "and accelerated): official ratios of record, remaining cuts, and destination win tally."
        ),
        "window_utc": {
            "first_row_completed": min(timestamps) if timestamps else None,
            "last_row_completed": max(timestamps) if timestamps else None,
        },
        "raw_sources": {
            "campaign_csv": os.path.relpath(csv_path, REPO).replace("\\", "/"),
            "load_samples": os.path.relpath(load_path, REPO).replace("\\", "/")
            if load_path
            else None,
        },
        "currency_artifact": os.path.relpath(REF, REPO).replace("\\", "/"),
        "identities": STAMPED_IDENTITIES,
        "protocol": {
            "cells": 8,
            "tools": TOOLS,
            "runs_per_cell_tool": 3,
            "warmups_per_cell_tool": 1,
            "threads": 12,
            "interleaved": True,
            "measured_rows": len(measured),
            "warmup_rows": len(warmups),
        },
        "cells": cells,
        "ranges": {
            "ratio_ordinary_over_orca": [
                round(min(ord_ratios), 4),
                round(max(ord_ratios), 4),
            ],
            "ratio_accelerated_over_orca": [
                round(min(acc_ratios), 4),
                round(max(acc_ratios), 4),
            ],
            "cpu_ratio_ordinary_over_orca": [
                round(min(ord_cpu_ratios), 4),
                round(max(ord_cpu_ratios), 4),
            ],
            "cpu_ratio_accelerated_over_orca": [
                round(min(acc_cpu_ratios), 4),
                round(max(acc_cpu_ratios), 4),
            ],
            "accel_vs_ordinary_wall_pct": [min(deltas), max(deltas)],
            "accel_vs_ordinary_cpu_pct": [min(cpu_deltas), max(cpu_deltas)],
        },
        "destination_tally": {
            "ordinary_wall_wins": len(ord_wall_wins),
            "ordinary_wall_win_cells": ord_wall_wins,
            "ordinary_cpu_corroborated_wins": len(ord_dest_wins),
            "ordinary_cpu_corroborated_win_cells": ord_dest_wins,
            "accelerated_wall_wins": len(acc_wall_wins),
            "accelerated_wall_win_cells": acc_wall_wins,
            "accelerated_cpu_corroborated_wins": len(acc_dest_wins),
            "accelerated_cpu_corroborated_win_cells": acc_dest_wins,
        },
        "identity": {
            "ordinary_all_eight": all(v["identity_ordinary"] for v in cells.values()),
            "accelerated_all_eight": all(
                v["identity_accelerated"] for v in cells.values()
            ),
            "ordinary_missing": [
                k for k, v in cells.items() if not v["identity_ordinary"]
            ],
            "accelerated_missing": [
                k for k, v in cells.items() if not v["identity_accelerated"]
            ],
            "code_1200_total": sum(
                v["code_1200_count_ordinary"] + v["code_1200_count_accelerated"]
                for v in cells.values()
            ),
        },
        "matched_keys": {
            "all_eight": all(v["orca_matched_keys_ok"] for v in cells.values()),
        },
        "box_load_pct": {
            "samples": len(load_pcts),
            "min": round(min(load_pcts), 1) if load_pcts else None,
            "median": round(statistics.median(load_pcts), 1) if load_pcts else None,
            "max": round(max(load_pcts), 1) if load_pcts else None,
        },
        "free_memory_mb": {
            "samples": len(free_mb),
            "min": round(min(free_mb), 1) if free_mb else None,
            "median": round(statistics.median(free_mb), 1) if free_mb else None,
            "max": round(max(free_mb), 1) if free_mb else None,
        },
        "cells_accelerated_faster": sum(1 for d in deltas if d < 0),
        "cells_accelerated_slower": sum(1 for d in deltas if d > 0),
    }

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as fh:
        json.dump(summary, fh, indent=1)
        fh.write("\n")

    print("wrote %s (%s)" % (out_path, window_label))
    for cell in CELL_ORDER:
        c = cells[cell]
        print(
            "%-20s orca %6.3fs  ord %6.3fs (%5.3fx, cut %+6.2f%%, cpu %4.2fx)  "
            "acc %6.3fs (%5.3fx, cut %+6.2f%%, cpu %4.2fx) | acc-ord %+5.1f%% | id %s/%s"
            % (
                cell,
                c["orca"]["wall_median_s"],
                c["pnp-ordinary"]["wall_median_s"],
                c["ratio_ordinary_over_orca"],
                c["required_cut_ordinary_pct"],
                c["cpu_ratio_ordinary_over_orca"],
                c["pnp-accelerated"]["wall_median_s"],
                c["ratio_accelerated_over_orca"],
                c["required_cut_accelerated_pct"],
                c["cpu_ratio_accelerated_over_orca"],
                c["accel_vs_ordinary_wall_pct"],
                "OK" if c["identity_ordinary"] else "MISS",
                "OK" if c["identity_accelerated"] else "MISS",
            )
        )
    dt = summary["destination_tally"]
    print(
        "wall wins: ord %d/8 %s | acc %d/8 %s ; cpu-corroborated: ord %d/8 | acc %d/8"
        % (
            dt["ordinary_wall_wins"],
            dt["ordinary_wall_win_cells"],
            dt["accelerated_wall_wins"],
            dt["accelerated_wall_win_cells"],
            dt["ordinary_cpu_corroborated_wins"],
            dt["accelerated_cpu_corroborated_wins"],
        )
    )
    print(
        "identity 16/16: %s/%s  code1200=%d  matched_keys=%s  load=%s  free_mb=%s"
        % (
            summary["identity"]["ordinary_all_eight"],
            summary["identity"]["accelerated_all_eight"],
            summary["identity"]["code_1200_total"],
            summary["matched_keys"]["all_eight"],
            summary["box_load_pct"],
            summary["free_memory_mb"],
        )
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--batch")
    ap.add_argument("--load")
    ap.add_argument("--out")
    ap.add_argument("--window", default="quiet")
    args = ap.parse_args()

    if args.batch:
        reduce_batch(args.batch, args.load, args.out, args.window)
        return

    quiet_csv = os.path.join(
        REPO, "target", "matched-pair", "t174-quiet-board", "scoreboard-rows.csv"
    )
    if os.path.exists(quiet_csv):
        reduce_batch(
            "t174-quiet-board",
            os.path.join(HERE, "reduced", "load-samples.csv"),
            os.path.join(HERE, "reduced", "summary.json"),
            "quiet",
        )
    loaded_csv = os.path.join(
        REPO,
        "target",
        "matched-pair",
        "t174-post-t172-scoreboard",
        "scoreboard-rows.csv",
    )
    if os.path.exists(loaded_csv):
        reduce_batch(
            "t174-post-t172-scoreboard",
            os.path.join(HERE, "reduced", "loaded-window-load-samples.csv"),
            os.path.join(HERE, "reduced", "loaded-window.json"),
            "loaded-first-take",
        )


if __name__ == "__main__":
    main()
