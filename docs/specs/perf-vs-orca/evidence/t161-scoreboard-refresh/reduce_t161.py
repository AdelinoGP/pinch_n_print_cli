#!/usr/bin/env python3
"""Reduce the t161 campaign into the reduced artifact the map quotes.

In-repo inputs (required):
  docs/specs/perf-vs-orca/evidence/t151-skirt-hull-contour/reference.json
      the active matched-job reference set (the currency this board checks)
  <this dir>/reduced/load-samples.csv
      box-load samples recorded during the campaign (timestamp, load_pct, free_kb)

Raw inputs (gitignored, regenerated by run_scoreboard.ps1):
  target/matched-pair/t161-scoreboard/scoreboard-rows.csv
  target/matched-pair/t161-scoreboard/stats/*.json
  target/matched-pair/t161-scoreboard/*.stderr.jsonl

Writes:
  reduced/summary.json

Definitions (kept identical to reduce_t145.py so the tables are comparable):
  ratio              = median(PnP wall) / median(Orca wall)
  required_cut_pct   = 100 * (1 - 1/ratio)
  required_cut_1.5x  = 100 * (1 - 1.5/ratio)
"""

import csv
import glob
import json
import os
import statistics
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", "..", "..", ".."))
REF = os.path.join(
    REPO,
    "docs",
    "specs",
    "perf-vs-orca",
    "evidence",
    "t151-skirt-hull-contour",
    "reference.json",
)
RUN_DIR = os.path.join(REPO, "target", "matched-pair", "t161-scoreboard")
CSV = os.path.join(RUN_DIR, "scoreboard-rows.csv")
LOAD = os.path.join(HERE, "reduced", "load-samples.csv")
CONTROL_CSV = os.path.join(REPO, "target", "matched-pair", "t161-statecontrol", "scoreboard-rows.csv")
OUT = os.path.join(HERE, "reduced", "summary.json")

CELL_ORDER = [
    "benchy-classic-off",
    "benchy-classic-on",
    "benchy-arachne-off",
    "benchy-arachne-on",
    "base-classic-off",
    "base-classic-on",
    "base-arachne-off",
    "base-arachne-on",
]

# The matched job the driver asserts on both arms (ticket 130 / 135 / 139 / 148).
EXPECTED_KEYS = {
    "resolved_brim_width": "8",
    "resolved_brim_type": "outer_only",
    "resolved_skirt_loops": "6",
    "resolved_skirt_distance": "3",
    "resolved_skirt_height": "1",
    "resolved_initial_layer_line_width": "0.4",
    "resolved_tree_support_brim_width": "0",
    "resolved_enable_arc_fitting": "disabled",
    "resolved_elefant_foot_compensation": "0",
}


def fnum(v):
    v = (v or "").strip()
    if not v:
        return None
    try:
        return float(v)
    except ValueError:
        return None


def read_rows():
    if not os.path.exists(CSV):
        sys.exit("missing campaign csv: %s" % CSV)
    with open(CSV, newline="", encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))


def count_diagnostics(stderr_path):
    """Count exact-Z occupancy rejection lines in a run's stderr jsonl."""
    if not stderr_path or not os.path.exists(stderr_path):
        return None
    n = 0
    with open(stderr_path, encoding="utf-8", errors="replace") as f:
        for line in f:
            if "exact-Z occupancy" in line:
                n += 1
    return n


def count_support_demands(stderr_path):
    """Sum the reported (body, demand) pair counts when present."""
    if not stderr_path or not os.path.exists(stderr_path):
        return None
    total = 0
    seen = False
    with open(stderr_path, encoding="utf-8", errors="replace") as f:
        for line in f:
            if "exact-Z occupancy" not in line:
                continue
            seen = True
            low = line.lower()
            for marker in ("pairs", "rejections", "entries"):
                i = low.find(marker)
                if i > 0:
                    j = i
                    while j > 0 and (low[j - 1].isdigit() or low[j - 1] in " _,"):
                        j -= 1
                    chunk = low[j:i].replace(",", "").replace("_", "").strip()
                    try:
                        total += int(chunk.split()[-1])
                    except (ValueError, IndexError):
                        pass
                    break
    return total if seen else None


def spread_pct(values):
    if len(values) < 2:
        return None
    m = statistics.median(values)
    if not m:
        return None
    return round(100.0 * (max(values) - min(values)) / m, 2)


def state_control():
    """Box-state control: one cell re-run after the batch, both tools.

    Not a second measurement of record - it answers whether the window's slower
    state persists or was transient.
    """
    if not os.path.exists(CONTROL_CSV):
        return None
    with open(CONTROL_CSV, newline="", encoding="utf-8-sig") as f:
        rows = [r for r in csv.DictReader(f) if r.get("warmup") == "0"]
    pnp = [fnum(r["wall_seconds"]) for r in rows if r.get("tool") == "pnp-ordinary"]
    orca = [fnum(r["wall_seconds"]) for r in rows if r.get("tool") == "orca"]
    if not pnp or not orca:
        return None
    pm, om = statistics.median(pnp), statistics.median(orca)
    return {
        "cell": "benchy-classic-off",
        "purpose": "box-state control taken after the batch: did the window's slower state persist?",
        "pnp_wall_s": [round(x, 4) for x in pnp],
        "orca_wall_s": [round(x, 4) for x in orca],
        "pnp_wall_median_s": round(pm, 4),
        "orca_wall_median_s": round(om, 4),
        "ratio_pnp_over_orca": round(pm / om, 4),
        "pnp_cpu_s": [round(fnum(r["cpu_seconds"]), 4) for r in rows if r.get("tool") == "pnp-ordinary"],
    }


def main():
    rows = read_rows()
    ref = json.load(open(REF, encoding="utf-8"))["active_set"]

    measured = [r for r in rows if r.get("warmup", "").lower() in ("false", "0")]
    warmups = [r for r in rows if r not in measured]

    cells = {}
    for cell in CELL_ORDER:
        fixture, generator, supports = cell.split("-")
        cell_rows = [
            r
            for r in measured
            if r.get("fixture") == fixture
            and r.get("cell") == generator + "-" + supports
        ]
        pnp = [r for r in cell_rows if r.get("tool") == "pnp-ordinary"]
        orca = [r for r in cell_rows if r.get("tool") == "orca"]

        entry = {
            "fixture": fixture,
            "generator": generator,
            "supports": supports,
            "pnp_runs": len(pnp),
            "orca_runs": len(orca),
            "pnp_wall_s": [round(fnum(r["wall_seconds"]), 4) for r in pnp],
            "pnp_cpu_s": [round(fnum(r["cpu_seconds"]), 4) for r in pnp],
            "orca_wall_s": [round(fnum(r["wall_seconds"]), 4) for r in orca],
        }

        if pnp and orca:
            pw = [fnum(r["wall_seconds"]) for r in pnp]
            pc = [fnum(r["cpu_seconds"]) for r in pnp]
            ow = [fnum(r["wall_seconds"]) for r in orca]
            pm, om = statistics.median(pw), statistics.median(ow)
            ratio = pm / om
            entry.update(
                {
                    "pnp_wall_median_s": round(pm, 4),
                    "orca_wall_median_s": round(om, 4),
                    "pnp_cpu_median_s": round(statistics.median(pc), 4),
                    "ratio_pnp_over_orca": round(ratio, 4),
                    "required_cut_pct": round(100 * (1 - 1 / ratio), 2),
                    "required_cut_1_5x_pct": round(100 * (1 - 1.5 / ratio), 2),
                    "pnp_spread_pct": spread_pct(pw),
                    "orca_spread_pct": spread_pct(ow),
                }
            )

        # output identity against the currency
        hashes = sorted({(r.get("sha256_of_gcode") or "").strip() for r in pnp})
        hashes = [h for h in hashes if h]
        entry["pnp_hashes"] = hashes
        entry["reference_hash"] = ref.get(cell)
        entry["identity"] = bool(ref.get(cell)) and hashes == [ref[cell]]

        # cleanliness
        entry["pnp_exit_codes"] = sorted({r.get("exit_code", "") for r in pnp})
        entry["orca_exit_codes"] = sorted({r.get("exit_code", "") for r in orca})
        entry["pnp_degraded"] = sorted({r.get("degraded", "") for r in pnp})
        entry["diagnostics_1200"] = [
            count_diagnostics(r.get("stderr_path", "")) for r in pnp
        ]
        entry["support_demand_pairs"] = [
            count_support_demands(r.get("stderr_path", "")) for r in pnp
        ]

        # matched keys, asserted from each arm's own resolved appendix
        key_audit = {}
        for key, want in EXPECTED_KEYS.items():
            got = sorted({(r.get(key) or "").strip() for r in orca})
            key_audit[key] = {
                "expected": want,
                "resolved": got,
                "ok": got == [want] if got else False,
            }
        entry["orca_matched_keys"] = key_audit
        entry["orca_matched_keys_ok"] = all(v["ok"] for v in key_audit.values())

        cells[cell] = entry

    ratios = [
        v["ratio_pnp_over_orca"] for v in cells.values() if "ratio_pnp_over_orca" in v
    ]
    cuts = [v["required_cut_pct"] for v in cells.values() if "required_cut_pct" in v]
    cuts15 = [
        v["required_cut_1_5x_pct"]
        for v in cells.values()
        if "required_cut_1_5x_pct" in v
    ]
    benchy = [
        v["ratio_pnp_over_orca"]
        for k, v in cells.items()
        if k.startswith("benchy") and "ratio_pnp_over_orca" in v
    ]
    base = [
        v["ratio_pnp_over_orca"]
        for k, v in cells.items()
        if k.startswith("base") and "ratio_pnp_over_orca" in v
    ]

    load = []
    if os.path.exists(LOAD):
        with open(LOAD, newline="", encoding="utf-8-sig") as f:
            for r in csv.reader(f):
                if len(r) >= 2 and r[1].strip():
                    load.append(r)
    load_pcts = [float(r[1]) for r in load if fnum(r[1]) is not None]

    summary = {
        "ticket": 161,
        "generated_by": "reduce_t161.py",
        "question": "Post-t158 eight-cell scoreboard on the current tree, one window.",
        "raw_sources": {
            "campaign_csv": os.path.relpath(CSV, REPO).replace("\\", "/"),
            "stats_dir": os.path.relpath(os.path.join(RUN_DIR, "stats"), REPO).replace(
                "\\", "/"
            ),
            "load_samples": os.path.relpath(LOAD, REPO).replace("\\", "/"),
        },
        "currency_artifact": os.path.relpath(REF, REPO).replace("\\", "/"),
        "protocol": {
            "cells": len(CELL_ORDER),
            "tools": ["orca", "pnp-ordinary"],
            "runs_per_cell": 3,
            "warmups_per_cell_tool": 1,
            "interleaved": True,
            "ordinary_arm_only": True,
            "measured_rows": len(measured),
            "warmup_rows": len(warmups),
        },
        "cells": cells,
        "ranges": {
            "ratio_overall": [round(min(ratios), 4), round(max(ratios), 4)]
            if ratios
            else None,
            "ratio_benchy": [round(min(benchy), 4), round(max(benchy), 4)]
            if benchy
            else None,
            "ratio_base": [round(min(base), 4), round(max(base), 4)] if base else None,
            "required_cut_pct": [min(cuts), max(cuts)] if cuts else None,
            "required_cut_1_5x_pct": [min(cuts15), max(cuts15)] if cuts15 else None,
        },
        "identity": {
            "all_eight": all(v["identity"] for v in cells.values()),
            "cells_matching": [k for k, v in cells.items() if v["identity"]],
            "cells_missing": [k for k, v in cells.items() if not v["identity"]],
        },
        "matched_keys": {
            "all_eight": all(v["orca_matched_keys_ok"] for v in cells.values()),
        },
        "box_load_pct": {
            "samples": len(load_pcts),
            "min": round(min(load_pcts), 1) if load_pcts else None,
            "median": round(statistics.median(load_pcts), 1) if load_pcts else None,
            "max": round(max(load_pcts), 1) if load_pcts else None,
        },
        "state_control": state_control(),
        "cells_won": sum(
            1
            for v in cells.values()
            if "ratio_pnp_over_orca" in v and v["ratio_pnp_over_orca"] <= 1.0
        ),
    }

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=1)

    print("wrote %s" % OUT)
    for cell in CELL_ORDER:
        c = cells[cell]
        if "ratio_pnp_over_orca" not in c:
            print(
                "%-22s INCOMPLETE (pnp=%d orca=%d)"
                % (cell, c["pnp_runs"], c["orca_runs"])
            )
            continue
        print(
            "%-22s pnp %8.3f  orca %8.3f  %5.3fx  cut %5.2f%%  id=%s %s"
            % (
                cell,
                c["pnp_wall_median_s"],
                c["orca_wall_median_s"],
                c["ratio_pnp_over_orca"],
                c["required_cut_pct"],
                "OK" if c["identity"] else "MISS",
                ""
                if not c.get("pnp_spread_pct")
                else "spread %.1f%%" % c["pnp_spread_pct"],
            )
        )
    print(
        "identity 8/8: %s   matched keys 8/8: %s   cells won: %d"
        % (
            summary["identity"]["all_eight"],
            summary["matched_keys"]["all_eight"],
            summary["cells_won"],
        )
    )


if __name__ == "__main__":
    main()
