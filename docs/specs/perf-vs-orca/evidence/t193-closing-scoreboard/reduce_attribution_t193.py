#!/usr/bin/env python3
"""Reduce the t193 attribution probe (`benchy-classic-on`) into one JSON.

Raw inputs (gitignored, regenerated by the two commands in REPRODUCE.md):
  target/t193-attr/instrument.stderr.jsonl
  target/t193-attr/profile.stderr.log
  target/t193-attr/benchy-classic-on.gcode

Writes:
  reduced/attribution.json
"""

import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", "..", "..", ".."))
ATTR = os.path.join(REPO, "target", "t193-attr")
OUT = os.path.join(HERE, "reduced", "attribution.json")
REF = os.path.join(
    REPO,
    "docs",
    "specs",
    "perf-vs-orca",
    "evidence",
    "t182-spatial-hierarchical-phase3-union",
    "reference.json",
)
CELL = "benchy-classic-on"


def json_events(path):
    events = []
    if not os.path.exists(path):
        sys.exit("missing instrumented stream: %s" % path)
    with open(path, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            line = line.strip()
            if line.startswith("{"):
                try:
                    events.append(json.loads(line))
                except ValueError:
                    pass
    return events


def main():
    events = json_events(os.path.join(ATTR, "instrument.stderr.jsonl"))
    phases = {}
    postpass_stages = {}
    for e in events:
        if e.get("event") == "phase_complete":
            phases[e.get("phase")] = e.get("elapsed_ms")
        if e.get("event") == "stage_complete" and e.get("phase") == "postpass":
            name = e.get("stage")
            postpass_stages[name] = postpass_stages.get(name, 0) + int(
                e.get("elapsed_ms") or 0
            )

    complete = [e for e in events if e.get("event") == "slice_complete"]
    if len(complete) != 1:
        sys.exit("expected exactly one slice_complete event, found %d" % len(complete))
    slice_complete = complete[0]

    profile_events = json_events(os.path.join(ATTR, "profile.stderr.log"))
    summaries = [e for e in profile_events if e.get("event") == "profile_summary"]
    if len(summaries) != 1:
        sys.exit("expected exactly one profile_summary, found %d" % len(summaries))
    profile = summaries[0]["profile"]
    modules = {m["module_id"]: m for m in profile["modules"]}

    with open(REF, encoding="utf-8") as fh:
        ref = json.load(fh)

    gcode_path = os.path.join(ATTR, "benchy-classic-on.gcode")
    if not os.path.exists(gcode_path):
        sys.exit("missing attribution gcode: %s" % gcode_path)
    with open(gcode_path, "rb") as fh:
        blob = fh.read()
    gcode_sha = hashlib.sha256(blob).hexdigest()

    total = slice_complete.get("elapsed_ms")
    outside = total - sum(
        phases.get(p, 0) for p in ("validation", "prepass", "per_layer", "postpass")
    )

    def module_fuel(module_id):
        m = modules.get(module_id)
        return m["total_fuel"] if m else None

    doc = {
        "ticket": 193,
        "cell": CELL,
        "generated_by": "reduce_attribution_t193.py",
        "raw_sources": {
            "instrument_stream": "target/t193-attr/instrument.stderr.jsonl",
            "profile_stream": "target/t193-attr/profile.stderr.log",
            "gcode": "target/t193-attr/benchy-classic-on.gcode",
        },
        "instrumented": {
            "elapsed_ms": total,
            "phases_ms": {
                k: phases.get(k)
                for k in ("validation", "prepass", "per_layer", "postpass")
            },
            "outside_brackets_ms": outside,
            "postpass_stages_ms": postpass_stages,
        },
        "profile": {
            "fuel_total": profile["fuel_total"],
            "wall_total_ns": profile["wall_total_ns"],
            "module_fuel": {
                "com.core.part-cooling": module_fuel("com.core.part-cooling"),
                "com.core.machine-gcode-emit": module_fuel(
                    "com.core.machine-gcode-emit"
                ),
                "com.core.classic-perimeters": module_fuel(
                    "com.core.classic-perimeters"
                ),
                "com.core.infill-linker": module_fuel("com.core.infill-linker"),
                "com.core.tree-support": module_fuel("com.core.tree-support"),
            },
        },
        "output": {
            "sha256_of_gcode": gcode_sha,
            "reference_sha256": ref["active_set"][CELL],
            "bytes": len(blob),
            "reference_bytes": ref["bytes"][CELL],
            "matches_reference": gcode_sha == ref["active_set"][CELL]
            and len(blob) == ref["bytes"][CELL],
        },
    }

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        json.dump(doc, fh, indent=1)
        fh.write("\n")
    print("wrote %s" % OUT)
    print(
        "elapsed=%d ms prepass=%d per_layer=%d postpass=%d outside=%d"
        % (
            total,
            phases.get("prepass", 0),
            phases.get("per_layer", 0),
            phases.get("postpass", 0),
            outside,
        )
    )
    print(
        "postpass stages: %s"
        % ", ".join("%s=%d" % (k, v) for k, v in sorted(postpass_stages.items()))
    )
    print("hash match: %s" % doc["output"]["matches_reference"])


if __name__ == "__main__":
    main()
