    dropped_warmups = 0
    for row in raw_rows:
        if row.get("warmup") == "1":
            key = (row.get("fixture"), row.get("cell"), row.get("tool"))
            if key in warmup_slot:
                all_rows[warmup_slot[key]] = row
                dropped_warmups += 1
                continue
            warmup_slot[key] = len(all_rows)
        all_rows.append(row)

