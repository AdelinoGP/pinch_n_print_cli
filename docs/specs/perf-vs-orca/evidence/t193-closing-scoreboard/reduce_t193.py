def fnum(v):
    v = (v or "").strip()
    if not v:
        return None
    try:
        return float(v)
    except ValueError:
        return None


def spread_pct(values):
    if len(values) < 2:
        return None
    m = statistics.median(values)
    if not m:
        return None
    return round(100.0 * (max(values) - min(values)) / m, 2)


def count_code_1200(stderr_path):
    if not stderr_path or not os.path.exists(stderr_path):
        return None
    hits = 0
    with open(stderr_path, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            if (
                '"code":1200' in line
                or '"code": 1200' in line
                or "exact-Z occupancy" in line
            ):
                hits += 1
    return hits


def read_support_style(run_dir, run_id):
    p = os.path.join(run_dir, "stats", run_id + ".json")
    if not os.path.exists(p):
        return None
    with open(p, encoding="utf-8-sig") as fh:
        data = json.load(fh)
    return (data.get("appendix") or {}).get("support_style")


def arm_block(rows, tool):
    trows = sorted(
        [r for r in rows if r.get("tool") == tool],
        key=lambda r: int(r.get("run_index") or 0),
    )
    walls = [fnum(r["wall_seconds"]) for r in trows]
    cpus = [fnum(r["cpu_seconds"]) for r in trows]
    ratios = [fnum(r["cpu_wall_ratio"]) for r in trows]
    if not walls:
        return None
    best_ratio = max(ratios)
    starved = [i for i, r in enumerate(ratios) if best_ratio and r < 0.75 * best_ratio]
    retained = [i for i in range(len(walls)) if i not in starved]
    if not retained:
        retained = list(range(len(walls)))
    kept_walls = [walls[i] for i in retained]
    kept_cpus = [cpus[i] for i in retained]
    kept_ratios = [ratios[i] for i in retained]
    return {
        "runs": len(walls),
        "retained_runs": len(retained),
        "retained_indices": retained,
        "wall_s": [round(w, 4) for w in walls],
        "cpu_s": [round(c, 4) for c in cpus],
        "cpu_wall_ratio": [round(r, 4) for r in ratios],
        "retained_wall_s": [round(w, 4) for w in kept_walls],
        "retained_cpu_s": [round(c, 4) for c in kept_cpus],
        "wall_median_s": round(statistics.median(kept_walls), 4),
        "cpu_median_s": round(statistics.median(kept_cpus), 4),
        "cpu_wall_ratio_median": round(statistics.median(kept_ratios), 4),
        "wall_median_all_s": round(statistics.median(walls), 4),
        "cpu_median_all_s": round(statistics.median(cpus), 4),
        "wall_spread_pct": spread_pct(kept_walls),
        "cpu_spread_pct": spread_pct(kept_cpus),
        "starved_indices_075": starved,
    }


