    warmups = [r for r in all_rows if r.get("warmup") == "1"]

    cells = {}
    for cell in CELL_ORDER:
        fixture, generator, supports = cell.split("-")
        m_rows = [
            r
            for r in measured
            if r.get("fixture") == fixture
            and r.get("cell") == generator + "-" + supports
        ]
        all_cell_rows = [
            r
            for r in all_rows
            if r.get("fixture") == fixture
            and r.get("cell") == generator + "-" + supports
        ]
        entry = {"fixture": fixture, "generator": generator, "supports": supports}

        for tool in TOOLS:
            block = arm_block(m_rows, tool)
            if block:
                entry[tool] = block

        ordinary = entry.get("pnp-ordinary")
        accelerated = entry.get("pnp-accelerated")
        orca = entry.get("orca")

        if ordinary and orca:
            wr = ordinary["wall_median_s"] / orca["wall_median_s"]
            cr = ordinary["cpu_median_s"] / orca["cpu_median_s"]
            entry["ratio_ordinary_over_orca"] = round(wr, 4)
            entry["cpu_ratio_ordinary_over_orca"] = round(cr, 4)
            entry["required_cut_ordinary_pct"] = round(100.0 * (1.0 - 1.0 / wr), 2)
            entry["margin_vs_t192_estimate_pct"] = round(
                100.0 * (wr / T192_ROUTE_ESTIMATE[cell][0] - 1.0), 2
            )
            entry["wall_win_ordinary"] = (
                ordinary["wall_median_s"] < orca["wall_median_s"]
            )
            entry["strict_separation_ordinary"] = max(
                ordinary["retained_wall_s"]
            ) < min(orca["retained_wall_s"])
            entry["retained_runs_ok_ordinary"] = (
                ordinary["retained_runs"] >= 4 and orca["retained_runs"] >= 4
            )
            entry["cpu_corroborates_ordinary"] = (
                ordinary["cpu_median_s"] < orca["cpu_median_s"]
            )
            if wr <= 0.85:
                entry["margin_tier_ordinary"] = "wide"
            elif wr < 1.0:
                entry["margin_tier_ordinary"] = "close"
            else:
                entry["margin_tier_ordinary"] = "loss"
        if accelerated and orca:
            wr = accelerated["wall_median_s"] / orca["wall_median_s"]
            cr = accelerated["cpu_median_s"] / orca["cpu_median_s"]
            entry["ratio_accelerated_over_orca"] = round(wr, 4)
            entry["cpu_ratio_accelerated_over_orca"] = round(cr, 4)
            entry["required_cut_accelerated_pct"] = round(100.0 * (1.0 - 1.0 / wr), 2)
            entry["margin_vs_t192_estimate_accelerated_pct"] = round(
                100.0 * (wr / T192_ROUTE_ESTIMATE[cell][1] - 1.0), 2
            )
            entry["wall_win_accelerated"] = (
                accelerated["wall_median_s"] < orca["wall_median_s"]
            )
            entry["strict_separation_accelerated"] = max(
                accelerated["retained_wall_s"]
            ) < min(orca["retained_wall_s"])
            entry["retained_runs_ok_accelerated"] = (
                accelerated["retained_runs"] >= 4 and orca["retained_runs"] >= 4
            )
            entry["cpu_corroborates_accelerated"] = (
                accelerated["cpu_median_s"] < orca["cpu_median_s"]
            )
            if wr <= 0.85:
                entry["margin_tier_accelerated"] = "wide"
            elif wr < 1.0:
                entry["margin_tier_accelerated"] = "close"
            else:
                entry["margin_tier_accelerated"] = "loss"
