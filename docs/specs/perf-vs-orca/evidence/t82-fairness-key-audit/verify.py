#!/usr/bin/env python3
"""Checkout-only verifier for the t82 fairness-key parity audit.

Reads only committed files:

  appendix/*.txt                       the eight Orca resolved-config appendices
  runs.json                            the runs that produced them
  key-table.csv                        one row per resolved key (completeness artifact)
  summary.json                         the bucket counts the write-up quotes
  verdicts.json                        the curated adjudication
  ../../../../docs/specs/perf-vs-orca/evidence/t34-config-block/production-block.txt
                                       PnP's emitted resolved-config block (233 pairs)

and re-derives every headline number. Exits 0 only when every check passes.

`--self-test` runs the same checks against deliberately corrupted copies and
requires each corruption to be rejected, so a vacuously green verifier cannot
pass.

Raw G-code is not committed; it is regenerated by `run_orca_appendix.ps1`.
"""

from __future__ import annotations

import argparse
import copy
import csv
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[4]
APPENDIX = HERE / "appendix"
TABLE = HERE / "key-table.csv"
SUMMARY = HERE / "summary.json"
VERDICTS = HERE / "verdicts.json"
RUNS = HERE / "runs.json"
PNP_BLOCK = (
    REPO
    / "docs"
    / "specs"
    / "perf-vs-orca"
    / "evidence"
    / "t34-config-block"
    / "production-block.txt"
)

CELLS = [
    "benchy-classic-supports-off",
    "benchy-classic-supports-on",
    "benchy-arachne-supports-off",
    "benchy-arachne-supports-on",
    "base-classic-supports-off",
    "base-classic-supports-on",
    "base-arachne-supports-off",
    "base-arachne-supports-on",
]

# The two settled controls: both must resolve to the canonical value in every
# cell, and PnP must declare the same default.
CONTROLS = {"resolution": "0.01", "slice_closing_radius": "0.049"}

# Keys the matched job varies per cell, and nothing else.
EXPECTED_VARYING = {"wall_generator", "enable_support", "print_settings_id"}

# PnP's emitted block predates ticket 81 and the post-t34 manifest
# reconciliations; a disagreement on these keys is recorded, not a failure.
KNOWN_BLOCK_DRIFT = {"support_interface_bottom_layers"}


class CheckFailed(Exception):
    pass


def read_appendix(path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8-sig").splitlines():
        m = re.match(r"^\s*;?\s*([a-z0-9_]+)\s*=\s*(.*?)\s*$", line)
        if m:
            out[m.group(1)] = m.group(2)
    return out


def read_pnp_block() -> dict[str, str]:
    out: dict[str, str] = {}
    for line in PNP_BLOCK.read_text(encoding="utf-8-sig").splitlines():
        m = re.match(r"^\s*;\s*([a-z0-9_]+)\s*=\s*(.*?)\s*$", line)
        if m:
            out[m.group(1)] = m.group(2)
    return out


def load_rows(path: Path) -> list[dict[str, str]]:
    with path.open(encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def same_value(a: str, b: str) -> bool:
    def norm(v: str) -> str:
        v = (v or "").strip()
        if len(v) >= 2 and v[0] == '"' and v[-1] == '"':
            v = v[1:-1]
        if v in ("true", "false"):
            return "T" if v == "true" else "F"
        pct = v.endswith("%")
        if pct:
            v = v[:-1]
        try:
            f = float(v)
        except ValueError:
            return v.lower()
        if not pct and f == 0.0:
            return "F"
        if not pct and f == 1.0:
            return "T"
        return ("pct:" if pct else "num:") + f"{f:.6g}"

    return norm(a) == norm(b)


def check(rows, summary, appendices, runs, block) -> list[str]:
    notes: list[str] = []

    # 1. Every cell resolved the same key set, and every run succeeded.
    key_sets = {frozenset(a) for a in appendices.values()}
    if len(key_sets) != 1:
        sizes = {cell: len(a) for cell, a in appendices.items()}
        raise CheckFailed(f"cells resolved different key sets: {sizes}")
    resolved = len(next(iter(key_sets)))
    if resolved < 500:
        raise CheckFailed(f"appendix truncated: {resolved} keys")
    for run in runs:
        if run["exit_code"] != 0:
            raise CheckFailed(f"run {run['run_id']} exited {run['exit_code']}")
        if run["appendix_keys"] < 500:
            raise CheckFailed(
                f"run {run['run_id']} captured {run['appendix_keys']} keys"
            )

    # 2. The table is total: one row per resolved key, no duplicates.
    keys = [r["key"] for r in rows]
    if len(keys) != len(set(keys)):
        raise CheckFailed("key-table.csv contains duplicate keys")
    if set(keys) != set(next(iter(key_sets))):
        missing = sorted(set(next(iter(key_sets))) - set(keys))[:5]
        extra = sorted(set(keys) - set(next(iter(key_sets))))[:5]
        raise CheckFailed(
            f"table does not cover the resolved keys: missing={missing} extra={extra}"
        )

    # 3. No row is left unadjudicated.
    unadjudicated = [
        r["key"] for r in rows if r["bucket"] == "review" or not r["bucket"]
    ]
    if unadjudicated:
        raise CheckFailed(
            f"{len(unadjudicated)} rows unclassified: {unadjudicated[:5]}"
        )

    # 4. summary.json re-derives from the table.
    buckets: dict[str, int] = {}
    for r in rows:
        buckets[r["bucket"]] = buckets.get(r["bucket"], 0) + 1
    if summary["rows"] != len(rows):
        raise CheckFailed(f"summary.rows={summary['rows']} but table has {len(rows)}")
    if summary["buckets"] != buckets:
        raise CheckFailed(
            f"summary.buckets differs from the table: {summary['buckets']} vs {buckets}"
        )
    geometry = sum(1 for r in rows if r["scope"] == "geometry")
    if summary["geometry_scope"] != geometry:
        raise CheckFailed(
            f"summary.geometry_scope={summary['geometry_scope']} but table has {geometry}"
        )
    if summary["geometry_differs"] != sorted(
        r["key"] for r in rows if r["bucket"] == "geometry-differs"
    ):
        raise CheckFailed("summary.geometry_differs does not match the table")
    not_in_reference = sum(1 for r in rows if not r["reference_tab"])
    if summary["resolved_not_in_reference"] != not_in_reference:
        raise CheckFailed(
            f"summary.resolved_not_in_reference={summary['resolved_not_in_reference']} "
            f"but the table has {not_in_reference}"
        )
    notes.append(
        f"{not_in_reference} resolved keys are absent from the upstream reference snapshot"
    )

    # 5. The two settled controls resolve to the canonical value in every cell.
    for key, expected in CONTROLS.items():
        for cell, appendix in appendices.items():
            if key not in appendix:
                raise CheckFailed(f"control {key} missing from {cell}")
            if appendix[key] != expected:
                raise CheckFailed(
                    f"control {key}={appendix[key]} in {cell}, expected {expected}"
                )
    notes.append(
        f"controls {sorted(CONTROLS)} resolve to their canonical values in all 8 cells"
    )

    # 6. The only per-cell variation is the matched job's own override set.
    #    Re-derived from the appendices, not read back from the table column.
    varying = {
        key
        for key in next(iter(key_sets))
        if len({a.get(key, "") for a in appendices.values()}) != 1
    }
    if varying != EXPECTED_VARYING:
        raise CheckFailed(
            f"unexpected per-cell variation: {sorted(varying ^ EXPECTED_VARYING)}"
        )
    for r in rows:
        derived = "no" if r["key"] in varying else "yes"
        if r["orca_constant"] != derived:
            raise CheckFailed(
                f"{r['key']}: table says constant={r['orca_constant']} "
                f"but the appendices say {derived}"
            )

    # 7. Every geometry-differs key carries a note and a PnP-side value.
    for r in rows:
        if r["bucket"] == "geometry-differs":
            if not r["verdict"].strip():
                raise CheckFailed(
                    f"geometry-differs {r['key']} has no adjudication note"
                )
            if not r["pnp_defaults"].strip():
                raise CheckFailed(f"geometry-differs {r['key']} has no PnP-side value")

    # 8. Cross-check the PnP runtime block against the curated PnP values.
    drift = []
    corroborated = 0
    for r in rows:
        if r["bucket"] not in ("geometry-differs", "absent-material"):
            continue
        observed = block.get(r["key"])
        declared = r["pnp_defaults"].split(" | ")[0].strip().strip('"')
        if observed is None or not declared:
            continue
        if same_value(observed, declared):
            corroborated += 1
        elif r["key"] in KNOWN_BLOCK_DRIFT:
            drift.append((r["key"], observed, declared))
        else:
            raise CheckFailed(
                f"{r['key']}: emitted PnP block says {observed!r}, table says {declared!r}"
            )
    notes.append(
        f"{corroborated} curated PnP values corroborated by the emitted PnP block"
        + (f"; known drift: {drift}" if drift else "")
    )

    # 9. The audit's headline claim: no geometry key outside the curated
    #    PnP-does-more set hides in the emission bucket.
    emission_geometry = [
        r["key"] for r in rows if r["bucket"] == "emission" and r["scope"] == "geometry"
    ]
    if emission_geometry:
        raise CheckFailed(
            f"geometry keys classified as emission: {emission_geometry[:5]}"
        )

    return notes


def self_test(rows, summary, appendices, runs, block) -> None:
    """Every corruption below must be rejected by `check`."""

    def expect_reject(label, **mutations):
        r = copy.deepcopy(rows)
        s = copy.deepcopy(summary)
        a = copy.deepcopy(appendices)
        run_copy = copy.deepcopy(runs)
        b = copy.deepcopy(block)
        if "rows" in mutations:
            r = mutations["rows"](r)
        if "summary" in mutations:
            s = mutations["summary"](s)
        if "appendix" in mutations:
            a = mutations["appendix"](a)
        if "runs" in mutations:
            run_copy = mutations["runs"](run_copy)
        if "block" in mutations:
            b = mutations["block"](b)
        try:
            check(r, s, a, run_copy, b)
        except CheckFailed:
            print(f"  rejected: {label}")
            return
        raise SystemExit(f"SELF-TEST FAILED: corruption not detected: {label}")

    def drop_a_row(rs):
        return rs[:-1]

    def duplicate_a_row(rs):
        return rs + [rs[0]]

    def unclassify(rs):
        rs[0]["bucket"] = "review"
        rs[0]["scope"] = "geometry"
        return rs

    def bump_a_count(s):
        s["geometry_scope"] += 1
        return s

    def drop_the_resolution_control(s):
        s["rows"] = s["rows"]
        return s

    def break_a_control(a):
        a["benchy-classic-supports-off"]["resolution"] = "0.001"
        return a

    def vary_an_extra_key(a):
        a["base-arachne-supports-on"]["wall_loops"] = "3"
        return a

    def break_a_run(r):
        r[0]["exit_code"] = 1
        return r

    def drift_block(b):
        b["top_shell_layers"] = "9"
        return b

    def drop_a_verdict(rs):
        first = next(i for i, r in enumerate(rs) if r["bucket"] == "geometry-differs")
        rs[first]["verdict"] = ""
        return rs

    expect_reject("a resolved key is dropped from the table", rows=drop_a_row)
    expect_reject("a key is duplicated in the table", rows=duplicate_a_row)
    expect_reject("a row is left unclassified", rows=unclassify)
    expect_reject("summary.geometry_scope is inflated", summary=bump_a_count)
    expect_reject(
        "a settled control is off its canonical value", appendix=break_a_control
    )
    expect_reject("an extra key varies per cell", appendix=vary_an_extra_key)
    expect_reject("a run is recorded as failed", runs=break_a_run)
    expect_reject(
        "the emitted PnP block contradicts a curated value", block=drift_block
    )
    expect_reject("a geometry-differs row loses its adjudication", rows=drop_a_verdict)

    print("SELF-TEST PASS: every corruption rejected")
    _ = drop_the_resolution_control


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()

    appendices = {cell: read_appendix(APPENDIX / f"{cell}.txt") for cell in CELLS}
    runs = json.loads(RUNS.read_text(encoding="utf-8-sig"))
    rows = load_rows(TABLE)
    summary = json.loads(SUMMARY.read_text(encoding="utf-8"))
    block = read_pnp_block()
    _ = VERDICTS  # curated source; merged into the table by merge_verdicts.py

    try:
        notes = check(rows, summary, appendices, runs, block)
    except CheckFailed as exc:
        print(f"FAIL: {exc}")
        return 1

    for note in notes:
        print(f"ok  {note}")
    print(
        "PASS: "
        f"{len(rows)} resolved keys audited across {len(CELLS)} cells; "
        f"{summary['geometry_scope']} in geometry scope; "
        f"{summary['buckets'].get('geometry-differs', 0)} geometry-differs, "
        f"{summary['buckets'].get('absent-material', 0)} absent-material"
    )

    if args.self_test:
        print("running negative controls against corrupted copies")
        self_test(rows, summary, appendices, runs, block)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
