//! Deterministic, readable SCAD emission from typed recipes.
//!
//! The emitter is a pure function of the recipe: no clocks, no environment, no
//! random sources, no resource loads. Canonical units become exact millimetre
//! decimal text (see [`super`]) so a recipe never passes through `f32` before
//! the adapter's checked conversion.

use std::fmt::Write as _;

use slicer_scad::{ScadEvalOptions, ScadEvalOutput, ScadSource};

use super::{
    check_bounds, invalid_bounds, invalid_input, required_adapter_capacity, validate_recipe,
    Recipe2d, Recipe3d, RecipeBounds, ScadRecipe, ScriptedError,
};
use super::super::domains::DomainError;

/// The stable diagnostic label every emitted program carries.
pub const RECIPE_LABEL: &str = "recipe.scad";

const PROGRAM_HEADER: &str =
    "// recipe.scad\n// generated by slicer-sdk scripted property support\n";

/// Format canonical units as an exact millimetre decimal.
///
/// `12345` units is `1.2345` mm. The text is generated from the integer, never
/// from an `f32`/`f64` round trip, and always carries exactly four fractional
/// digits so equal units always produce identical bytes.
fn millimetres(units: i64) -> String {
    let sign = if units < 0 { "-" } else { "" };
    let magnitude = units.unsigned_abs();
    let whole = magnitude / 10_000;
    let fraction = magnitude % 10_000;
    format!("{sign}{whole}.{fraction:04}")
}

fn unsigned_millimetres(units: u32) -> String {
    millimetres(i64::from(units))
}

struct Emitter {
    out: String,
    limit: usize,
}

impl Emitter {
    fn new(limit: usize) -> Self {
        let mut out = String::with_capacity(limit.min(4096));
        out.push_str(PROGRAM_HEADER);
        Self { out, limit }
    }

    fn push(&mut self, text: &str) -> Result<(), ScriptedError> {
        if self.out.len() + text.len() > self.limit {
            return Err(invalid_bounds(format!(
                "emitted source exceeds max_source_bytes {}",
                self.limit
            )));
        }
        self.out.push_str(text);
        Ok(())
    }

    fn open(&mut self, call: &str) -> Result<(), ScriptedError> {
        self.push(call)?;
        self.push("{\n")
    }

    fn close(&mut self) -> Result<(), ScriptedError> {
        self.push("}\n")
    }

    fn finish(self) -> String {
        self.out
    }
}

fn emit2d(recipe: &Recipe2d, emitter: &mut Emitter) -> Result<(), ScriptedError> {
    match recipe {
        Recipe2d::Rectangle { size_units } => {
            let mut text = String::new();
            let _ = writeln!(
                text,
                "square([{}, {}]);",
                unsigned_millimetres(size_units[0]),
                unsigned_millimetres(size_units[1])
            );
            emitter.push(&text)
        }
        Recipe2d::Disk {
            radius_units,
            facets,
        } => {
            let mut text = String::new();
            let _ = writeln!(
                text,
                "circle(r = {}, $fn = {facets});",
                unsigned_millimetres(*radius_units)
            );
            emitter.push(&text)
        }
        Recipe2d::Polygon { polygons } => {
            if polygons.is_empty() {
                return Err(invalid_input(
                    "a polygon leaf needs at least one component; use an empty Union for Empty",
                ));
            }
            emitter.open("union()")?;
            for polygon in polygons {
                emit_component(&polygon.contour, &polygon.holes, emitter)?;
            }
            emitter.close()
        }
        Recipe2d::Translate {
            offset_units,
            child,
        } => {
            let mut text = String::new();
            let _ = writeln!(
                text,
                "translate([{}, {}])",
                millimetres(offset_units[0]),
                millimetres(offset_units[1])
            );
            emitter.push(&text)?;
            emit2d(child, emitter)
        }
        Recipe2d::QuarterTurn { turns, child } => {
            let angle = i32::from(*turns) * 90;
            let mut text = String::new();
            let _ = writeln!(text, "rotate([0, 0, {angle}])");
            emitter.push(&text)?;
            emit2d(child, emitter)
        }
        Recipe2d::Union(children) | Recipe2d::Intersection(children) => {
            let call = if matches!(recipe, Recipe2d::Union(_)) {
                "union()"
            } else {
                "intersection()"
            };
            emitter.open(call)?;
            for child in children {
                emit2d(child, emitter)?;
            }
            emitter.close()
        }
        Recipe2d::Difference { base, cuts } => {
            emitter.open("difference()")?;
            emit2d(base, emitter)?;
            for cut in cuts {
                emit2d(cut, emitter)?;
            }
            emitter.close()
        }
    }
}

fn emit_component(
    contour: &slicer_ir::Polygon,
    holes: &[slicer_ir::Polygon],
    emitter: &mut Emitter,
) -> Result<(), ScriptedError> {
    if holes.is_empty() {
        return emit_polygon(contour, emitter);
    }
    emitter.open("difference()")?;
    emit_polygon(contour, emitter)?;
    for hole in holes {
        emit_polygon(hole, emitter)?;
    }
    emitter.close()
}

fn emit_polygon(ring: &slicer_ir::Polygon, emitter: &mut Emitter) -> Result<(), ScriptedError> {
    let mut text = String::from("polygon([");
    for (index, point) in ring.points.iter().enumerate() {
        if index > 0 {
            text.push_str(", ");
        }
        let _ = write!(
            text,
            "[{}, {}]",
            millimetres(point.x),
            millimetres(point.y)
        );
    }
    text.push_str("]);\n");
    emitter.push(&text)
}

fn emit3d(recipe: &Recipe3d, emitter: &mut Emitter) -> Result<(), ScriptedError> {
    match recipe {
        Recipe3d::Box { size_units } => {
            let mut text = String::new();
            let _ = writeln!(
                text,
                "cube([{}, {}, {}]);",
                unsigned_millimetres(size_units[0]),
                unsigned_millimetres(size_units[1]),
                unsigned_millimetres(size_units[2])
            );
            emitter.push(&text)
        }
        Recipe3d::Cylinder {
            radius_units,
            height_units,
            facets,
        } => {
            let mut text = String::new();
            let _ = writeln!(
                text,
                "cylinder(h = {}, r = {}, $fn = {facets});",
                unsigned_millimetres(*height_units),
                unsigned_millimetres(*radius_units)
            );
            emitter.push(&text)
        }
        Recipe3d::LinearExtrude {
            height_units,
            profile,
        } => {
            let mut text = String::new();
            let _ = writeln!(
                text,
                "linear_extrude(height = {})",
                unsigned_millimetres(*height_units)
            );
            emitter.push(&text)?;
            emit2d(profile, emitter)
        }
        Recipe3d::Translate {
            offset_units,
            child,
        } => {
            let mut text = String::new();
            let _ = writeln!(
                text,
                "translate([{}, {}, {}])",
                millimetres(offset_units[0]),
                millimetres(offset_units[1]),
                millimetres(offset_units[2])
            );
            emitter.push(&text)?;
            emit3d(child, emitter)
        }
        Recipe3d::QuarterTurnZ { turns, child } => {
            let angle = i32::from(*turns) * 90;
            let mut text = String::new();
            let _ = writeln!(text, "rotate([0, 0, {angle}])");
            emitter.push(&text)?;
            emit3d(child, emitter)
        }
        Recipe3d::Union(children) | Recipe3d::Intersection(children) => {
            let call = if matches!(recipe, Recipe3d::Union(_)) {
                "union()"
            } else {
                "intersection()"
            };
            emitter.open(call)?;
            for child in children {
                emit3d(child, emitter)?;
            }
            emitter.close()
        }
        Recipe3d::Difference { base, cuts } => {
            emitter.open("difference()")?;
            emit3d(base, emitter)?;
            for cut in cuts {
                emit3d(cut, emitter)?;
            }
            emitter.close()
        }
    }
}

/// Emit a bounded, readable, self-contained SCAD program for `recipe`.
///
/// The result is a pure function of `recipe` and `bounds`: identical inputs
/// always produce identical bytes. The program has no resource loads, ambient
/// variables, text/font requests, loops, recursion or random programs, and
/// every faceted primitive carries its explicit facet count.
///
/// # Errors
/// Returns [`ScriptedError::Domain`] when the recipe is out of bounds, has a
/// non-positive primitive dimension, more than three quarter turns, too few
/// facets, or when the emitted text would exceed `bounds.max_source_bytes`.
pub fn emit_scad(recipe: &ScadRecipe, bounds: &RecipeBounds) -> Result<ScadSource, ScriptedError> {
    validate_recipe(recipe, bounds)?;
    let mut emitter = Emitter::new(bounds.max_source_bytes);
    match recipe {
        ScadRecipe::Contours(recipe) => emit2d(recipe, &mut emitter)?,
        ScadRecipe::Solid(recipe) => emit3d(recipe, &mut emitter)?,
    }
    let text = emitter.finish();
    if text.len() > bounds.max_source_bytes {
        return Err(invalid_bounds("emitted source exceeds max_source_bytes"));
    }
    Ok(ScadSource {
        label: RECIPE_LABEL.to_string(),
        text,
    })
}

/// Emit `recipe` and evaluate it through the public adapter.
///
/// This is not another renderer: it calls [`slicer_scad::evaluate`] with the
/// supplied options and returns its full checked output. The caller owns
/// process containment when the work must be killable; these helper calls make
/// no in-process cancellation promise.
///
/// # Errors
/// Returns [`ScriptedError::Domain`] for invalid recipes, bounds or option
/// capacities, and [`ScriptedError::Adapter`] for every rejection the adapter
/// reports, including partial, degraded, approximate and unclassified output.
pub fn evaluate_recipe(
    recipe: &ScadRecipe,
    options: &ScadEvalOptions,
    bounds: &RecipeBounds,
) -> Result<ScadEvalOutput, ScriptedError> {
    check_bounds(bounds)?;
    // Validate the adapter's own limits before spending a render.
    let capacity = required_adapter_capacity(bounds);
    if options.limits.max_ast_nodes < capacity.0 {
        return Err(invalid_bounds(format!(
            "adapter max_ast_nodes {} is below the {}-node emitter bound",
            options.limits.max_ast_nodes, capacity.0
        )));
    }
    if options.limits.max_ast_depth < capacity.1 {
        return Err(invalid_bounds(format!(
            "adapter max_ast_depth {} is below the {}-level emitter bound",
            options.limits.max_ast_depth, capacity.1
        )));
    }
    if options.limits.max_geometry_nodes < capacity.2 {
        return Err(invalid_bounds(format!(
            "adapter max_geometry_nodes {} is below the {}-node recipe bound",
            options.limits.max_geometry_nodes, capacity.2
        )));
    }
    if options.limits.max_facets < u32::from(bounds.max_facets) {
        return Err(invalid_bounds(format!(
            "adapter max_facets {} is below the recipe max_facets {}",
            options.limits.max_facets, bounds.max_facets
        )));
    }
    if options.limits.max_source_bytes < bounds.max_source_bytes {
        return Err(invalid_bounds(format!(
            "adapter max_source_bytes {} is below the recipe max_source_bytes {}",
            options.limits.max_source_bytes, bounds.max_source_bytes
        )));
    }
    let source = emit_scad(recipe, bounds)?;
    let output = slicer_scad::evaluate(&source, options)?;
    check_dimensionality(recipe, &output)?;
    Ok(output)
}

fn check_dimensionality(
    recipe: &ScadRecipe,
    output: &ScadEvalOutput,
) -> Result<(), ScriptedError> {
    use slicer_scad::ScadGeometry;
    let consistent = matches!(
        (recipe, &output.geometry),
        (_, ScadGeometry::Empty)
            | (ScadRecipe::Contours(_), ScadGeometry::Contours(_))
            | (ScadRecipe::Solid(_), ScadGeometry::Mesh(_))
    );
    if consistent {
        Ok(())
    } else {
        Err(ScriptedError::Domain(DomainError::InvalidInput(
            "recipe dimensionality does not match the adapter output".into(),
        )))
    }
}
